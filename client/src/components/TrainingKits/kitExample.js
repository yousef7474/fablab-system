const gear = (cx, cy, r, teeth, color) => {
  const pts = [];
  for (let i = 0; i < teeth * 2; i++) {
    const a = (Math.PI * i) / teeth;
    const rr = i % 2 ? r : r + r * 0.18;
    pts.push(`${(cx + rr * Math.cos(a)).toFixed(1)},${(cy + rr * Math.sin(a)).toFixed(1)}`);
  }
  return `<polygon points="${pts.join(' ')}" fill="${color}" stroke="#0f172a" stroke-width="2"/><circle cx="${cx}" cy="${cy}" r="${(r * 0.25).toFixed(1)}" fill="#fff" stroke="#0f172a" stroke-width="2"/>`;
};
